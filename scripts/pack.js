#!/usr/bin/env node
'use strict';
/* Builds a ready-to-upload deployment zip with no tools and no network: node scripts/pack.js [output.zip]
   Files sit at the zip root (server.js is the start file). node_modules, tests, data and CI files are left out:
   CampusNet has no runtime dependencies to install (ws is vendored in vendor/ws). */
const fs = require('node:fs'), path = require('node:path');
const ROOT = path.join(__dirname, '..');
const INCLUDE = ['server.js', 'package.json', 'package-lock.json', 'Dockerfile', 'README.md', 'RELEASE_NOTES.md', 'DEPLOY.md', 'DEPLOY.fa.md', '.env.example', 'scripts/start.js', 'scripts/restore.js', 'index.js', 'lib', 'vendor', 'public'];
const walk = rel => { const abs = path.join(ROOT, rel); if (!fs.existsSync(abs)) return []; const st = fs.statSync(abs); return st.isDirectory() ? fs.readdirSync(abs).sort().flatMap(n => walk(rel + '/' + n)) : [rel]; };
const { zip } = require('../lib/zip');
const crypto = require('node:crypto');
const PUFFERLAND_DOC = 'PUFFERLAND.fa.md';
/* opts.pufferland = { admin, site, access }: adds index.js (the platform's default start file), a generated private .env and the Persian guide */
function build(opts = {}) {
  const names = INCLUDE.flatMap(walk), files = names.map(name => ({ name, data: fs.readFileSync(path.join(ROOT, name)) })), extra = {};
  const pf = opts.pufferland;
  if (pf) {
    extra.adminCode = pf.adminCode || crypto.randomBytes(18).toString('base64url');
    const env = ['# Generated by npm run pack:pufferland. Private: do not share this zip or this file.', `SITE_NAME=${pf.site || 'CampusNet'}`, 'TRUST_PROXY=1', `ADMIN_USERS=${pf.admin || 'admin'}`, `ADMIN_CODE=${extra.adminCode}`, pf.access ? `ACCESS_CODE=${pf.access}` : '# ACCESS_CODE=a-shared-join-code', 'BACKUP_EVERY_HOURS=24', 'BACKUP_KEEP=7', ''].join('\n');
    files.push({ name: '.env', data: Buffer.from(env) }, { name: PUFFERLAND_DOC, data: fs.readFileSync(path.join(ROOT, PUFFERLAND_DOC)) });
    names.push('.env', PUFFERLAND_DOC);
  }
  return { zip: zip(files), names, ...extra };
}
function parseArgs(argv) {
  const o = { pufferland: false, out: null }, take = k => argv[++k];
  for (let k = 0; k < argv.length; k++) {
    const a = argv[k];
    if (a === '--pufferland') o.pufferland = {}; else if (a === '--admin') (o.pufferland ||= {}).admin = take(k++); else if (a === '--site') (o.pufferland ||= {}).site = take(k++);
    else if (a === '--access') (o.pufferland ||= {}).access = take(k++); else if (a === '--admin-code') (o.pufferland ||= {}).adminCode = take(k++); else if (!a.startsWith('--')) o.out = a;
  }
  return o;
}
if (require.main === module) {
  const version = require('../package.json').version, args = parseArgs(process.argv.slice(2));
  const out = path.resolve(args.out || path.join(ROOT, 'dist', args.pufferland ? `campusnet-pufferland-${version}.zip` : `campusnet-${version}.zip`));
  const r = build({ pufferland: args.pufferland || undefined }); fs.mkdirSync(path.dirname(out), { recursive: true }); fs.writeFileSync(out, r.zip);
  console.log(`${out}\n${r.names.length} files, ${(r.zip.length / 1024).toFixed(0)} KB. ${args.pufferland ? 'Start file: index.js (the default). Admin code is inside .env' + (r.adminCode ? ': ' + r.adminCode : '') : 'Start file: server.js'}. No npm install needed.`);
}
module.exports = { build, parseArgs };
